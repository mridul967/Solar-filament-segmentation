register_coco_instances("filament_val", {}, val_split_json, TRAIN_IMG_DIR)

# Extract category names sorted by ID from the JSON already in memory
# COCO category IDs: 1 -> Left, 2 -> Right, 3 -> Unidentifiable, 4 -> Ambiguous
