# -------------------------------------------------------------------------
def predict_filament(
    image_path: str,
    min_area: int = 200,
    max_disjoint_blobs: int = 3,
    visualize: bool = True
):
    img = cv2.imread(image_path)
    if img is None:
        print(f"Error reading image: {image_path}")
        return None

    h, w = img.shape[:2]
    img_gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    solar_disk = get_solar_disk_mask(img_gray, margin=18)

    outputs = predictor(img)
    instances = outputs["instances"].to("cpu")

    if len(instances) == 0:
        print(f"\nImage: {os.path.basename(image_path)} | Filaments Detected: 0")
        return instances

    pred_masks = instances.pred_masks.numpy()
    scores = instances.scores.numpy()
    pred_classes = instances.pred_classes.numpy()
    boxes = instances.pred_boxes.tensor.numpy()

    # Sort instances descending by confidence for pixel priority
    order = np.argsort(-scores)
    pred_masks = pred_masks[order]
    scores = scores[order]
    pred_classes = pred_classes[order]
    boxes = boxes[order]

    occupied_canvas = np.zeros((h, w), dtype=bool)
    kept_masks = []
    kept_scores = []
    kept_classes = []
    kept_boxes = []

    for i in range(len(pred_masks)):
        mask = pred_masks[i].astype(np.uint8)

        # 1. Limb clipping: wipe out anything outside the bright solar disk
        mask = mask & solar_disk

        # 2. Reject confusing granulation noise (too many fragmented islands)
        num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(mask, connectivity=8)
        num_blobs = num_labels - 1
        if num_blobs == 0 or num_blobs > max_disjoint_blobs:
            continue

        # Keep the primary spine component, discard loose stray pixels
        main_blob_idx = 1 + np.argmax(stats[1:, cv2.CC_STAT_AREA])
        clean_mask = (labels == main_blob_idx)

        # 3. Strict zero-overlap guarantee
        exclusive_mask = clean_mask & (~occupied_canvas)

        # 4. Discard if area drops below threshold (prevents low-IoU PQ penalty)
        if int(exclusive_mask.sum()) < min_area:
            continue

        occupied_canvas |= exclusive_mask
        kept_masks.append(exclusive_mask)
        kept_scores.append(scores[i])
        kept_classes.append(pred_classes[i])
        kept_boxes.append(boxes[i])

    # Reconstruct filtered Detectron2 Instances object for clean visualization
    filtered_instances = Instances((h, w))
    if kept_masks:
        import torch
        filtered_instances.pred_masks = torch.as_tensor(np.stack(kept_masks), dtype=torch.bool)
        filtered_instances.scores = torch.as_tensor(kept_scores, dtype=torch.float32)
        filtered_instances.pred_classes = torch.as_tensor(kept_classes, dtype=torch.int64)
        from detectron2.structures import Boxes
        filtered_instances.pred_boxes = Boxes(torch.as_tensor(np.stack(kept_boxes), dtype=torch.float32))

    print(f"\nImage: {os.path.basename(image_path)} | Raw: {len(instances)} | Post-Processed Kept: {len(kept_masks)}")

    if visualize:
        v = Visualizer(img[:, :, ::-1], metadata=metadata, scale=0.5, instance_mode=ColorMode.IMAGE)
        out = v.draw_instance_predictions(filtered_instances)
        cv2_imshow(out.get_image()[:, :, ::-1])

    return filtered_instances

