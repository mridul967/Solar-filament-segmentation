# -------------------------------------------------------------------------
# 1. Grouped Train/Val Split (Prevents Multi-Annotator Data Leakage)
# -------------------------------------------------------------------------
ORIGINAL_TRAIN_JSON = "/content/dataset/MAGFiLO_1.0_Kaggle_2026/train/MAGFiLO_1.0_Annotations_kaggle2026_train.json"
TRAIN_IMG_DIR = "/content/dataset/MAGFiLO_1.0_Kaggle_2026/train/train_images"

with open(ORIGINAL_TRAIN_JSON, "r") as f:
    coco_data = json.load(f)

# Group image records by actual physical file_name
file_to_images = defaultdict(list)
for img in coco_data["images"]:
    file_to_images[img["file_name"]].append(img)

all_files = list(file_to_images.keys())
random.seed(42)
random.shuffle(all_files)

# 85% train / 15% validation by unique disk images
val_split_idx = int(len(all_files) * 0.85)
train_files = set(all_files[:val_split_idx])
val_files = set(all_files[val_split_idx:])

train_images = [img for fname in train_files for img in file_to_images[fname]]
val_images = [img for fname in val_files for img in file_to_images[fname]]

train_img_ids = {img["id"] for img in train_images}
val_img_ids = {img["id"] for img in val_images}

train_annotations = [ann for ann in coco_data["annotations"] if ann["image_id"] in train_img_ids]
val_annotations = [ann for ann in coco_data["annotations"] if ann["image_id"] in val_img_ids]

# Write out split JSONs
os.makedirs("/content/dataset/splits", exist_ok=True)
train_split_json = "/content/dataset/splits/train_split.json"
val_split_json = "/content/dataset/splits/val_split.json"

for path, imgs, anns in [(train_split_json, train_images, train_annotations), (val_split_json, val_images, val_annotations)]:
    with open(path, "w") as out_f:
        json.dump({
            "images": imgs,
            "annotations": anns,
            "categories": coco_data["categories"]
        }, out_f)

print(f"Grouped split ready: {len(train_files)} train unique images ({len(train_images)} records), {len(val_files)} val unique images ({len(val_images)} records)")


# -------------------------------------------------------------------------
# 2. Register Datasets in Detectron2
# -------------------------------------------------------------------------
for d in ["filament_train", "filament_val"]:
    if d in DatasetCatalog.list():
        DatasetCatalog.remove(d)
        MetadataCatalog.remove(d)

