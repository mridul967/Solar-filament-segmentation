MetadataCatalog.get("filament_val").set(thing_classes=thing_classes)

num_classes = len(thing_classes)  # 4
print(f"Registered classes: {thing_classes} (Count: {num_classes})")

# -------------------------------------------------------------------------
# 3. Model Architecture & Hyperparameter Customization
# -------------------------------------------------------------------------
cfg = get_cfg()
cfg.merge_from_file(model_zoo.get_config_file("COCO-InstanceSegmentation/mask_rcnn_R_50_FPN_3x.yaml"))

cfg.DATASETS.TRAIN = ("filament_train",)
cfg.DATASETS.TEST = ("filament_val",)
cfg.DATALOADER.NUM_WORKERS = 2
cfg.MODEL.WEIGHTS = model_zoo.get_checkpoint_url("COCO-InstanceSegmentation/mask_rcnn_R_50_FPN_3x.yaml")

# --- Filament-Specific Geometry Adjustments ---
# Higher mask head resolution to prevent topological breaking on narrow spines
cfg.MODEL.ROI_MASK_HEAD.POOLER_RESOLUTION = 28  # Default is 14 -> gives 56x56 masks instead of 28x28
# Wider aspect ratios to capture long solar neutral line filaments
cfg.MODEL.ANCHOR_GENERATOR.ASPECT_RATIOS = [[0.2, 0.5, 1.0, 2.0, 5.0]]

# --- Resolution Settings (Preserve thin filament barbs) ---
cfg.INPUT.MIN_SIZE_TRAIN = (1024, 1200)
cfg.INPUT.MAX_SIZE_TRAIN = 1344
cfg.INPUT.MIN_SIZE_TEST = 1024
cfg.INPUT.MAX_SIZE_TEST = 1024

# --- Optimization Settings ---
cfg.SOLVER.IMS_PER_BATCH = 2          # 2 images per step (fit inside 15-16GB Colab GPU VRAM)
cfg.SOLVER.BASE_LR = 0.0005           # Smooth start for R-50 backbone
cfg.SOLVER.WARMUP_ITERS = 300
cfg.SOLVER.MAX_ITER = 5000            # ~10 epochs over 980 train entries
cfg.SOLVER.STEPS = (3500, 4500)
cfg.SOLVER.GAMMA = 0.1
cfg.SOLVER.CHECKPOINT_PERIOD = 1000

# --- Classification & Inference ---
cfg.MODEL.ROI_HEADS.NUM_CLASSES = num_classes
cfg.MODEL.ROI_HEADS.BATCH_SIZE_PER_IMAGE = 256
cfg.MODEL.ROI_HEADS.SCORE_THRESH_TEST = 0.20  # Low threshold to capture faint filaments for PQ/Dice


# Save to a fresh folder so you preserve your 0.30 baseline checkpoint
cfg.OUTPUT_DIR = "./output_mask_rcnn_vanilla"
os.makedirs(cfg.OUTPUT_DIR, exist_ok=True)

# -------------------------------------------------------------------------
# 4. Execute Training
# -------------------------------------------------------------------------
trainer = DefaultTrainer(cfg)
trainer.resume_or_load(resume=False)
trainer.train()

