# 2. Grab Test Files
test_img_dir = "/content/dataset/MAGFiLO_1.0_Kaggle_2026/test/test_images"
test_image_paths = sorted(glob.glob(f"{test_img_dir}/*.png") + glob.glob(f"{test_img_dir}/*.jpg"))

# Sample 3 test images
random.seed(42)
sample_test_paths = random.sample(test_image_paths, min(3, len(test_image_paths)))

def mask_to_coco_rle(binary_mask: np.ndarray) -> str:
    fortran_mask = np.asfortranarray(binary_mask.astype(np.uint8))
    rle = mask_util.encode(fortran_mask)
    return rle["counts"].decode("utf-8")

# 3. Test Loop
test_sample_rows = []
MIN_FILAMENT_AREA = 100  # Minimum pixel area threshold

for path in sample_test_paths:
    filename = os.path.basename(path)
    img_id = os.path.splitext(filename)[0]
    img = cv2.imread(path)

    outputs = predictor(img)
    instances = outputs["instances"].to("cpu")

    pred_masks = instances.pred_masks.numpy() if instances.has("pred_masks") else []
    pred_scores = instances.scores.numpy() if instances.has("scores") else []
    pred_classes = instances.pred_classes.numpy() if instances.has("pred_classes") else []

    kept_indices = []
    filament_idx = 0

    for i, mask in enumerate(pred_masks):
        mask_area = np.sum(mask)
        if mask_area < MIN_FILAMENT_AREA:
            continue

        kept_indices.append(i)
        rle_str = mask_to_coco_rle(mask)

        test_sample_rows.append({
            "filament_id": f"{img_id}_{filament_idx}",
            "image_id": img_id,
            "class_id": int(pred_classes[i]),
            "confidence": float(round(pred_scores[i], 3)),
            "area_px": int(mask_area),
            "segmentation_rle": rle_str[:40] + "..."
        })
        filament_idx += 1

    print(f"\nImage: {filename} | Raw Detections: {len(pred_masks)} | Kept After Area Filter: {len(kept_indices)}")

    # Visualize even if 0 are kept so you can verify the raw detections
    filtered_instances = instances[kept_indices]
    v = Visualizer(img[:, :, ::-1], metadata=val_metadata, scale=0.5, instance_mode=ColorMode.IMAGE)
    out = v.draw_instance_predictions(filtered_instances)
    cv2_imshow(out.get_image()[:, :, ::-1])

# 4. Create DataFrame with explicit fallback columns
columns = ["filament_id", "image_id", "class_id", "confidence", "area_px", "segmentation_rle"]
df_preview = pd.DataFrame(test_sample_rows, columns=columns)

