# -------------------------------------------------------------------------
# 1. Config & Predictor Setup (Aligned with Screenshot Settings)
# -------------------------------------------------------------------------
OUTPUT_DIR = "./output_mask_rcnn_striphead"
WEIGHTS_PATH = os.path.join(OUTPUT_DIR, "model_final.pth")

cfg.OUTPUT_DIR = OUTPUT_DIR
cfg.MODEL.WEIGHTS = WEIGHTS_PATH
cfg.MODEL.ROI_HEADS.NUM_CLASSES = 4
# Matches the registered name used during training in the screenshot:
cfg.MODEL.ROI_MASK_HEAD.NAME = "SolarFilamentStripMaskHead_fixedloss"
cfg.MODEL.ROI_MASK_HEAD.POOLER_RESOLUTION = 28
cfg.MODEL.ANCHOR_GENERATOR.ASPECT_RATIOS = [[0.2, 0.5, 1.0, 2.0, 5.0]]
cfg.MODEL.ROI_HEADS.SCORE_THRESH_TEST = 0.20  # Matches training screenshot threshold
cfg.MODEL.ROI_HEADS.NMS_THRESH_TEST = 0.35
cfg.MODEL.DEVICE = "cuda"

print(f"Loading weights from: {cfg.MODEL.WEIGHTS}")
predictor = DefaultPredictor(cfg)

# -------------------------------------------------------------------------
# 2. Parameters & Helper Functions
# -------------------------------------------------------------------------
TEST_DIR = "/content/dataset/MAGFiLO_1.0_Kaggle_2026/test/test_images"
OUT_SUBMISSION_PATH = "/content/submission_striphead_fixedloss.csv"
ORIGINAL_SIZE = 2048
MIN_AREA_2048 = 200          # Prunes tiny false-positive specks
MAX_DISJOINT_BLOBS = 3      # Rejects fragmented granulation noise

def pycoco_rle_encode(binary_mask: np.ndarray) -> str:
    fortran_mask = np.asfortranarray(binary_mask.astype(np.uint8))
    rle = maskUtils.encode(fortran_mask)
    return rle["counts"].decode("utf-8")

def get_solar_disk_mask(img_gray, margin=18):
    _, thresh = cv2.threshold(img_gray, 25, 255, cv2.THRESH_BINARY)
    contours, _ = cv2.findContours(thresh, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
    if not contours:
        return np.ones_like(img_gray, dtype=bool)
    c = max(contours, key=cv2.contourArea)
    (x, y), radius = cv2.minEnclosingCircle(c)
    disk = np.zeros_like(img_gray, dtype=np.uint8)
    cv2.circle(disk, (int(x), int(y)), int(radius - margin), 255, -1)
    return disk > 0

# -------------------------------------------------------------------------
# 3. Discover Test Images & Run Inference
# -------------------------------------------------------------------------
valid_exts = ('.jpeg', '.jpg', '.png')
test_image_paths = sorted([
    os.path.join(TEST_DIR, f) for f in os.listdir(TEST_DIR)
    if f.lower().endswith(valid_exts)
])

print(f"Generating full submission across {len(test_image_paths)} test images...")

submissions = []

for img_path in tqdm(test_image_paths, desc="Processing Test Set"):
    base_id = os.path.splitext(os.path.basename(img_path))[0]
    img = cv2.imread(img_path)
    if img is None:
        continue

    # 1. Solar limb boundary mask
    img_gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    solar_disk = get_solar_disk_mask(img_gray, margin=18)

    outputs = predictor(img)
    instances = outputs["instances"].to("cpu")

    if len(instances) == 0:
        continue

    scores = instances.scores.numpy()
    pred_masks = instances.pred_masks.numpy()

    # Sort descending by confidence so top predictions get canvas priority
    order = np.argsort(-scores)
    pred_masks = pred_masks[order]

    occupied_canvas = np.zeros((ORIGINAL_SIZE, ORIGINAL_SIZE), dtype=bool)
    filament_idx = 1

    for i in range(len(pred_masks)):
        mask_native = pred_masks[i]

        # Upscale back to native 2048x2048
        if mask_native.shape != (ORIGINAL_SIZE, ORIGINAL_SIZE):
            mask_2048 = cv2.resize(
                mask_native.astype(np.uint8),
                (ORIGINAL_SIZE, ORIGINAL_SIZE),
                interpolation=cv2.INTER_NEAREST
            )
        else:
            mask_2048 = mask_native.astype(np.uint8)

        # 2. Eliminate limb artifacts outside solar circle
        mask_2048 = mask_2048 & solar_disk

        # 3. Reject fragmented granulation noise
        num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(mask_2048, connectivity=8)
        num_blobs = num_labels - 1
        if num_blobs == 0 or num_blobs > MAX_DISJOINT_BLOBS:
            continue

        # Keep primary spine component, strip disjoint satellite specks
        main_blob_idx = 1 + np.argmax(stats[1:, cv2.CC_STAT_AREA])
        clean_mask = (labels == main_blob_idx)

        # 4. Strict zero-overlap canvas subtraction
        exclusive_mask = clean_mask & (~occupied_canvas)

        # 5. Filter if remaining area is too small to reach IoU > 0.5
        if int(exclusive_mask.sum()) < MIN_AREA_2048:
            continue

        # Mark canvas occupied and append row
        occupied_canvas |= exclusive_mask
        rle_str = pycoco_rle_encode(exclusive_mask)

        submissions.append({
            "filament_id": f"{base_id}_{filament_idx}",
            "segmentation_rle": rle_str
        })
        filament_idx += 1

# -------------------------------------------------------------------------
# 4. Save and Validate Output
# -------------------------------------------------------------------------
df_sub = pd.DataFrame(submissions, columns=["filament_id", "segmentation_rle"])
df_sub.to_csv(OUT_SUBMISSION_PATH, index=False)

