"""## 7. RLE Submission Helpers

Check the Kaggle **Submit Predictions** page before final submission. If the exact required column names differ, edit `SUBMISSION_COLUMNS`.
"""

SUBMISSION_COLUMNS = ["filament_id", "segmentation_rle"]


def encode_coco_rle(binary_mask):
    mask_f = np.asfortranarray(binary_mask.astype(np.uint8))
    rle = mask_utils.encode(mask_f)
    return rle["counts"].decode("utf-8")


def result_to_submission_rows(result, image_name, min_mask_area=20):
    rows = []
    if result.masks is None:
        return rows

    masks = result.masks.data.cpu().numpy()
    confs = result.boxes.conf.cpu().numpy() if result.boxes is not None else np.ones(len(masks), dtype=np.float32)
    orig_h, orig_w = result.orig_shape
    image_stem = Path(image_name).stem

    # Kaggle rejects overlapping instance masks. Keep high-confidence masks first,
    # then remove already-claimed pixels from lower-confidence masks.
    order = np.argsort(-confs)
    occupied = np.zeros((orig_h, orig_w), dtype=bool)

    for mask_index in order:
        mask_arr = masks[mask_index]
        if mask_arr.shape != (orig_h, orig_w):
            mask_arr = cv2.resize(mask_arr, (orig_w, orig_h), interpolation=cv2.INTER_NEAREST)

        binary = mask_arr > 0.5
        binary = np.logical_and(binary, ~occupied)
        if int(binary.sum()) < min_mask_area:
            continue

        occupied |= binary
        rows.append(
            {
                "filament_id": f"{image_stem}_{len(rows) + 1}",
                "segmentation_rle": encode_coco_rle(binary),
            }
        )
    return rows

"""## 8. Create Test Submission

This emits one row per predicted filament instance. If an image has no predicted instances, this notebook emits no rows for that image. If Kaggle requires one row per image, add an explicit empty-mask row after confirming the required format.
"""

def make_submission(model, test_img_dir, output_csv="submission_phase2_yolo_kaggle_nonoverlap.csv"):
    test_paths = sorted(
        list(Path(test_img_dir).glob("*.jpeg"))
        + list(Path(test_img_dir).glob("*.jpg"))
        + list(Path(test_img_dir).glob("*.png"))
    )
    print("Test images:", len(test_paths))

    rows = []
    for path in tqdm(test_paths, desc="test inference"):
        result = model.predict(
            source=str(path),
            imgsz=CFG["imgsz"],
            conf=CFG["confidence"],
            iou=CFG["iou"],
            retina_masks=True,
            device=DEVICE,
            verbose=False,
        )[0]
        rows.extend(result_to_submission_rows(result, path.name, min_mask_area=CFG["min_mask_area"]))

    sub = pd.DataFrame(rows, columns=SUBMISSION_COLUMNS)
    sub.to_csv(output_csv, index=False)
    return sub


