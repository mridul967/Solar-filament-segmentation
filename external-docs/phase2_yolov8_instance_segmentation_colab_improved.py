"""## 3. Convert COCO Polygons To YOLO-Seg Labels

YOLO segmentation labels use one text file per image.

Each object row is:

```text
class_id x1 y1 x2 y2 x3 y3 ...
```

Coordinates are normalized to `[0, 1]`. Since Kaggle evaluates masks only, every object gets class `0 = filament`.
"""

def clean_polygon(seg, width, height):
    points = np.asarray(seg, dtype=np.float32).reshape(-1, 2)
    if len(points) < 3:
        return None

    points[:, 0] = np.clip(points[:, 0], 0, width - 1)
    points[:, 1] = np.clip(points[:, 1], 0, height - 1)

    # Remove duplicate consecutive vertices. YOLO can be fussy about degenerate polygons.
    keep = [0]
    for i in range(1, len(points)):
        if np.linalg.norm(points[i] - points[keep[-1]]) > 1e-3:
            keep.append(i)
    points = points[keep]
    if len(points) < 3:
        return None

    points[:, 0] /= width
    points[:, 1] /= height
    return points


def annotation_to_yolo_rows(item):
    rows = []
    for ann in item["annotations"]:
        segs = ann.get("segmentation", [])
        if not isinstance(segs, list):
            continue
        for seg in segs:
            poly = clean_polygon(seg, item["width"], item["height"])
            if poly is None:
                continue
            coords = " ".join(f"{v:.6f}" for v in poly.reshape(-1))
            rows.append(f"0 {coords}")
    return rows


def reset_dir(path):
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True, exist_ok=True)


def copy_or_link(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        return
    try:
        os.symlink(src, dst)
    except Exception:
        shutil.copy2(src, dst)


def write_yolo_split(split_name, split_items):
    image_dir = YOLO_DATASET_DIR / "images" / split_name
    label_dir = YOLO_DATASET_DIR / "labels" / split_name
    image_dir.mkdir(parents=True, exist_ok=True)
    label_dir.mkdir(parents=True, exist_ok=True)

    skipped = 0
    for item in tqdm(split_items, desc=f"write {split_name}"):
        image_dst = image_dir / item["file_name"]
        label_dst = label_dir / (Path(item["file_name"]).stem + ".txt")

        rows = annotation_to_yolo_rows(item)
        if not rows:
            skipped += 1
            continue

        copy_or_link(item["image_path"], image_dst)
        label_dst.write_text("\n".join(rows) + "\n")

    print(split_name, "images:", len(list(image_dir.glob('*'))), "labels:", len(list(label_dir.glob('*.txt'))), "skipped:", skipped)

